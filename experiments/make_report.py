h1("Phase 5  --  MILP Validation")
body("Goal: build an exact MILP formulation of the charge-scheduling problem, validate it on a "
     "hand-checkable instance, and measure the heuristic&#39;s optimality gap.")
h2("Hand-checkable instance, verified by hand")
body("4 drones, 2 stations x 1 pad, 60-minute horizon, dt=10min. Manual calculation: each "
     "drone needs exactly 2 charging slots to reach its target from its start SoC, so the true "
     "minimum is 4x2=8 pad-slots. <b>The solver found objective=8.0, exactly matching.</b>")
h2("A real bug, caught by the optimality-gap check itself")
body("The SoC recurrence was first written as a strict equality. On a harder 8-drone instance, "
     "the MILP reported <b>Infeasible</b> while the greedy heuristic found a solution that "
     "independently checked out as fully feasible. Since an exact solver should never call "
     "something infeasible when a feasible solution provably exists, this proved a MILP bug: "
     "the equality forced SoC to mathematically exceed 1.0 whenever a charging decision would "
     "physically overshoot full, instead of saturating like reality does. Fixed with an "
     "inequality. After the fix: the same instance gives MILP=13.0 (Optimal), heuristic=13 (0% gap).")
h2("Optimality gap: 0% across every feasible instance tested")
body("22 feasible instances across two sweeps (8 varied-size instances, then 15 more for "
     "robustness)  --  every single one at exactly 0% gap. The one remaining instance (tightest "
     "single-pad case) was correctly called Infeasible by both solvers, a useful cross-check in "
     "its own right.")
fig("fig6_phase5_gap.png",
    "Figure 6. Optimality gap distribution across all 22 feasible test instances  --  a single "
    "spike at exactly 0%.")
body("This is explained, not just observed: in this v1 MILP scope, every pad-slot costs exactly "
     "1 unit regardless of drone or station (no tariff/travel heterogeneity yet), so the only real "
     "decision is <i>who</i> gets scarce pad-time <i>when</i>  --  and prioritizing the most "
     "time-constrained drone first is a classical optimal rule for this kind of uniform-cost "
     "deadline-feasibility problem. This should not be over-generalized: it is a property of this "
     "simplified scope, not a general claim that the heuristic is optimal once costs (tariffs, "
     "travel, the CC-CV curve itself) become heterogeneous.")
h2("C9 (piecewise CC-CV) and C10 (charging continuity)")
body("Implemented after an <b>initially-documented C9 formulation turned out to be wrong</b> "
     " --  applying every charging band&#39;s rate as a simultaneous upper bound regardless of "
     "a drone&#39;s actual SoC would have forced every drone onto the slowest band&#39;s rate no "
     "matter how low their SoC. Caught before implementing, not after. The corrected version uses "
     "proper band-selection indicator variables. <b>Two more bugs</b> were found while building "
     "it: a free-SoC-jump hole when not charging (fixed), and a spurious-SoC-decrease hole with no "
     "discharge model to explain it (fixed with an explicit monotonicity constraint). Verified to "
     "reproduce v1&#39;s result exactly within a single band, and to require >= v1&#39;s pad-time "
     "once a drone must cross into a slower band.")
